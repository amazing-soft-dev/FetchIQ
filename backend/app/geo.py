UNITED_STATES = "United States"


def canonical_country(value: str) -> str | None:
    text = " ".join(value.strip().split())
    if not text:
        return None
    folded = text.casefold()
    if folded in COUNTRY_ALIASES:
        return COUNTRY_ALIASES[folded]
    for name in COUNTRIES:
        if name.casefold() == folded:
            return name
    return None


def canonical_state(value: str) -> str | None:
    text = " ".join(value.strip().split())
    if not text:
        return None
    folded = text.casefold().rstrip(".")
    if folded in STATE_ABBREVIATIONS:
        return STATE_ABBREVIATIONS[folded]
    for name in US_STATES:
        if name.casefold() == folded:
            return name
    return None


def is_united_states(country: str) -> bool:
    return country == UNITED_STATES
