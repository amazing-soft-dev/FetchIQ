"""The subset of the MongoDB driver surface FetchIQ uses, as Protocols.

Modules type their ``db`` against ``Database`` instead of importing a driver
class, so a driver change touches ``db.py`` and ``main.py`` only. The shapes
mirror PyMongo's ``AsyncMongoClient`` and ``mongomock-motor``; return values are
left as ``Any`` because the drivers return different result classes with the
same attributes.

Nothing here runs at runtime. ``runtime_checkable`` only lets tests assert
that a driver object has every method the app calls.
"""

from collections.abc import AsyncIterator, Mapping, Sequence
from typing import Any, Protocol, runtime_checkable

Document = dict[str, Any]
Filter = Mapping[str, Any]
Projection = Mapping[str, Any] | Sequence[str] | None


@runtime_checkable
class Cursor(Protocol):
    def __aiter__(self) -> AsyncIterator[Document]: ...
    def sort(self, key_or_list: Any, direction: Any = ...) -> "Cursor": ...
    def skip(self, skip: int) -> "Cursor": ...
    def limit(self, limit: int) -> "Cursor": ...
    async def to_list(self, length: int | None = ...) -> list[Document]: ...


@runtime_checkable
class Collection(Protocol):
    def find(
        self, filter: Filter | None = ..., projection: Projection = ..., **kwargs: Any
    ) -> Cursor: ...
    async def find_one(
        self, filter: Filter | None = ..., projection: Projection = ..., **kwargs: Any
    ) -> Document | None: ...
    async def find_one_and_update(
        self, filter: Filter, update: Mapping[str, Any], **kwargs: Any
    ) -> Any: ...
    async def insert_one(self, document: Mapping[str, Any], **kwargs: Any) -> Any: ...
    async def insert_many(self, documents: Sequence[Mapping[str, Any]], **kwargs: Any) -> Any: ...
    async def update_one(self, filter: Filter, update: Mapping[str, Any], **kwargs: Any) -> Any: ...
    async def update_many(
        self, filter: Filter, update: Mapping[str, Any], **kwargs: Any
    ) -> Any: ...
    async def delete_one(self, filter: Filter, **kwargs: Any) -> Any: ...
    async def delete_many(self, filter: Filter, **kwargs: Any) -> Any: ...
    async def count_documents(self, filter: Filter, **kwargs: Any) -> int: ...
    async def distinct(self, key: str, filter: Filter | None = ..., **kwargs: Any) -> list[Any]: ...
    async def create_index(self, keys: Any, **kwargs: Any) -> str: ...
    async def drop_index(self, index_or_name: Any, **kwargs: Any) -> None: ...
    async def index_information(self) -> dict[str, Any]: ...


@runtime_checkable
class Database(Protocol):
    name: str

    # Collections are reached as attributes (``db.search_jobs``), which every driver
    # resolves dynamically; declaring ``__getattr__`` types them without naming each.
    def __getattr__(self, name: str) -> Collection: ...
    def __getitem__(self, name: str) -> Collection: ...
    async def command(self, command: Any, *args: Any, **kwargs: Any) -> Any: ...


@runtime_checkable
class Client(Protocol):
    def __getitem__(self, name: str) -> Database: ...
    async def close(self) -> None: ...
